import { useCallback, useEffect, useState } from "react";
import axios from "axios";
import { Sparkles, RefreshCw, AlertTriangle, Upload } from "lucide-react";
import { useNavigate } from "react-router-dom";
import { apiUrl } from "../lib/apiPath";

const TONE = {
  Strong: "bg-green-50 text-green-700 border-green-200",
  Stable: "bg-blue-50 text-blue-700 border-blue-200",
  Cautious: "bg-amber-50 text-amber-700 border-amber-200",
  Concerning: "bg-red-50 text-red-700 border-red-200",
};

/** AI summary report (DeepSeek) of the statements generated from the current trial balance. */
export default function AISummaryCard() {
  const navigate = useNavigate();
  const [s, setS] = useState(null);
  const [state, setState] = useState("loading"); // loading | ready | empty | error
  const [error, setError] = useState("");

  const load = useCallback(async (refresh = false) => {
    setState("loading");
    try {
      const { data } = await axios.get(apiUrl(`/api/ai/summary${refresh ? "?refresh=1" : ""}`), { timeout: 180000 });
      if (data.empty) { setState("empty"); return; }
      setS(data); setState("ready");
    } catch (e) {
      setError(e.response?.data?.error || "The AI summary couldn't be generated right now.");
      setState("error");
    }
  }, []);
  useEffect(() => { load(); }, [load]);

  return (
    <section className="bg-white rounded-[14px] shadow-[0_1px_3px_rgba(0,0,0,0.08)] border border-[#E5E7EB]/60 overflow-hidden">
      <div className="flex flex-wrap items-center justify-between gap-3 px-5 lg:px-6 py-4 border-b border-[#E5E7EB] bg-gradient-to-r from-blue-50/60 to-purple-50/40">
        <div className="flex items-center gap-2.5">
          <span className="grid size-8 place-items-center rounded-lg bg-gradient-to-br from-[#2563EB] to-[#7C3AED] text-white"><Sparkles className="size-4" /></span>
          <div>
            <h3 className="text-base lg:text-lg font-semibold text-[#0F172A] leading-tight">AI Summary Report</h3>
            <p className="text-xs text-[#64748B]">
              {state === "ready" ? `${s.file} · generated ${new Date(s.generatedAt).toLocaleString("en-IN", { day: "2-digit", month: "short", hour: "2-digit", minute: "2-digit" })}` : "Generated by AI from your current trial balance"}
            </p>
          </div>
        </div>
        <div className="flex items-center gap-2">
          {state === "ready" && <span className={`px-3 py-1 text-xs font-semibold rounded-full border ${TONE[s.verdict] || TONE.Stable}`}>{s.verdict}</span>}
          {(state === "ready" || state === "error") && (
            <button onClick={() => load(true)} className="flex items-center gap-1.5 px-3 py-1.5 text-xs font-medium text-[#475569] border border-[#E5E7EB] rounded-lg hover:bg-white">
              <RefreshCw className="size-3.5" /> Regenerate
            </button>
          )}
        </div>
      </div>

      <div className="px-5 lg:px-6 py-5">
        {state === "loading" && (
          <div className="space-y-3 animate-pulse" aria-label="Generating summary">
            <div className="h-4 w-3/4 rounded bg-slate-100" />
            {[0, 1, 2, 3].map((i) => <div key={i} className="h-3 w-full rounded bg-slate-100" />)}
            <p className="text-xs text-[#64748B]">Reading the statements and writing the summary…</p>
          </div>
        )}
        {state === "empty" && (
          <div className="flex flex-wrap items-center justify-between gap-3 text-sm text-[#475569]">
            <span>Upload a trial balance to get an AI summary of its statements.</span>
            <button onClick={() => navigate("/dashboard/trial-balance/summary")} className="flex items-center gap-2 px-4 py-2 rounded-lg bg-[#2563EB] text-white text-sm font-medium"><Upload className="size-4" /> Upload trial balance</button>
          </div>
        )}
        {state === "error" && <p className="flex items-center gap-2 text-sm text-red-600"><AlertTriangle className="size-4" />{error}</p>}
        {state === "ready" && (
          <>
            <p className="text-[15px] font-medium text-[#0F172A] leading-relaxed">{s.headline}</p>
            <dl className="mt-4 grid gap-3 sm:grid-cols-2 lg:grid-cols-3">
              {s.points.map((p) => (
                <div key={p.title} className="rounded-xl border border-[#E5E7EB] bg-[#F8FAFC]/60 p-3.5">
                  <dt className="text-xs font-semibold uppercase tracking-wider text-[#2563EB]">{p.title}</dt>
                  <dd className="mt-1 text-sm text-[#334155] leading-relaxed">{p.text}</dd>
                </div>
              ))}
            </dl>
            {s.watch && (
              <p className="mt-4 flex gap-2 rounded-xl border border-amber-200 bg-amber-50 px-3.5 py-2.5 text-sm text-amber-800">
                <AlertTriangle className="size-4 mt-0.5 flex-shrink-0" /><span><strong className="font-semibold">Watch: </strong>{s.watch}</span>
              </p>
            )}
          </>
        )}
      </div>
    </section>
  );
}
